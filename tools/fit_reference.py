"""Generate the small fitting system from the private head reference extract_reference.py writes."""
import json
import struct
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
GROUPS = [
    ('right_eye', [428,624]), ('left_eye', [476,866]),
    ('right_cheek', [226,300,239]), ('left_cheek', [74,348,87]),
    ('right_jaw', [219,198,223]), ('left_jaw', [67,42,71]),
    ('chin', [35,187,27]), ('crown', [149]), ('back', [1210]),
]


def landmarks(vertices):
    v = np.asarray(vertices)
    return np.array([v[ids].mean(axis=0) for _,ids in GROUPS])


def system(points):
    n = len(points)
    p = np.column_stack((np.ones(n),points))
    matrix = np.zeros((n+4,n+4))
    square=np.sum((points[:,None]-points[None,:])**2,axis=2)
    matrix[:n,:n] = np.sqrt(square+1e-8)-.0001
    matrix[:n,n:] = p
    matrix[n:,:n] = p.T
    return matrix


if __name__ == '__main__':
    ref = json.loads((ROOT/'assets/source/headhuman.nif.json').read_text())[0]
    points = landmarks(ref['vertices']).round(6)
    inverse = np.linalg.inv(system(points))[:,:len(points)]
    def floats(row):
        return ','.join(f'{float(x):.9e}f' for x in row)
    lines = ['#pragma once', '//generated by tools/fit_reference.py', 'namespace XRay::Fit {',
             'static const float kCenters[kFitAnchors][4]={']
    lines += ['    {'+floats([*p,0])+'},' for p in points]
    lines += ['};', 'constexpr unsigned kChinLandmark=6;', 'struct Landmark {unsigned count;unsigned vertices[3];};',
              'static const Landmark kLandmarks[kFitAnchors]={']
    lines += ['    {'+str(len(ids))+',{'+','.join(map(str,ids+[0]*(3-len(ids))))+'}},' for _,ids in GROUPS]
    lines += ['};', 'static const float kSolve[kFitCoefficients][kFitAnchors]={']
    lines += ['    {'+floats(row)+'},' for row in inverse]
    lines += ['};', '}']
    (ROOT/'src/FitReference.h').write_text('\n'.join(lines)+'\n')
    output=ROOT/'tests/output/fit';output.mkdir(parents=True,exist_ok=True)
    with (output/'faces.bin').open('wb') as f:
        for name in ('headhuman.nif.json','headfemale.nif.json'):
            face=json.loads((ROOT/'assets/source'/name).read_text())[0]
            for point in landmarks(face['vertices']):f.write(struct.pack('<3f',*point))
    print('FIT_REFERENCE',len(points),'landmarks, condition',round(float(np.linalg.cond(system(points))),2))
