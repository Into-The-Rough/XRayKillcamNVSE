"""Generate src/HorseRest.h: each horse region's influence bones relative to its frame bone in the HAP horse's rest pose.

The horse anatomy is fitted to that rest pose, so a horse's region capture places each bone's anatomy through these relations.
Reads the rest pose tools/horse_fit.py wrote.

    python tools/horse_rest.py"""
import json
import sys
from pathlib import Path

import numpy

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from human_rest import literal

#the influence order of kHorseSpecs in src/Horse.cpp, frame bone first, None where a region names none
REGIONS = [
    ['Bip01 Head', 'Bip01 Jaw', 'Bip01 Neck2', 'Bip01 Neck1', 'Bip01 Neck', None, None],
    ['Bip01 Spine1', 'Bip01 Spine2', 'Bip01 Pelvis', 'Bip01 L Clavicle', 'Bip01 R Clavicle', 'Bip01 L Thigh', 'Bip01 R Thigh'],
    ['Bip01 Pelvis', 'Bip01 L Calf', 'Bip01 L HorseLink', 'Bip01 L Foot', 'Bip01 R Calf', 'Bip01 R HorseLink', 'Bip01 R Foot'],
    ['Bip01 Spine2', 'Bip01 L UpperArm', 'Bip01 L Forearm', 'Bip01 L Hand', 'Bip01 R UpperArm', 'Bip01 R Forearm', 'Bip01 R Hand'],
]


def main():
    rest = {n: numpy.array(m) for n, m in json.loads((ROOT / 'assets/source/extracted/horse/fitted.json').read_text())['rest'].items()}
    rows = []
    for bones in REGIONS:
        frame = rest[bones[0]]
        rows.append('{' + ','.join(literal(numpy.linalg.inv(rest[b]) @ frame) if b else literal(numpy.eye(4)) for b in bones) + '}')
    header = ['#pragma once', '//generated by tools/horse_rest.py from the HAP horse skeleton', '#include "Math.h"', '#include "Model.h"', '',
              'namespace XRay {', '//each horse region\'s influences in kHorseSpecs order, frame-local to bone-local in the horse\'s rest pose',
              'static const Transform kHorseRest[4][kInfluences]={', ',\n'.join('    ' + r for r in rows), '};', '}', '']
    (ROOT / 'src/HorseRest.h').write_text('\n'.join(header))
    print('HORSE_REST_OK', len(rows), 'regions')


if __name__ == '__main__':
    main()
